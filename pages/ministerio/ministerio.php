        <h3 class="display-8 mb-4">O desejo por um ministério não é, por si só, um chamado de Deus</h3>

        <p>É natural que um cristão deseje servir ao Senhor. A própria Escritura afirma que desejar o episcopado é desejar uma excelente obra (1 Timóteo 3:1). Entretanto, a Bíblia também ensina que existe uma grande diferença entre desejar servir e ser chamado por Deus para determinada função.</p>

        <p>Infelizmente, em muitos lugares, o ministério passou a ser visto como um reconhecimento público. Alguns desejam ser chamados de pastor, presbítero, evangelista ou diácono porque isso lhes concede respeito, influência ou destaque diante da igreja. O problema é que Deus nunca chamou alguém apenas para ocupar um título. Deus chama pessoas para carregar responsabilidades.</p>

        <p>É exatamente isso que Hebreus nos ensina:</p>
        <i>"Ninguém toma esta honra para si mesmo, senão quando é chamado por Deus." (Hebreus 5:4)</i>

        <p>O escritor está falando do sacerdócio, mostrando que essa honra não podia ser assumida por vontade própria. O princípio continua válido: as funções espirituais não existem para satisfazer desejos pessoais, mas para cumprir a vontade de Deus.</p>

        <p>Uma pessoa pode desejar muito ser pastor, mas isso não significa automaticamente que Deus a chamou para esse ministério. Da mesma forma, alguém pode desejar cantar, ensinar ou pregar, mas será necessário que Deus confirme esse chamado através do caráter, dos frutos, da maturidade espiritual e da aprovação da igreja.</p>

        <p>O chamado verdadeiro nunca começa pelo título; ele começa pelo serviço. Jesus nunca ensinou Seus discípulos a buscarem posições de destaque. Pelo contrário, ensinou que o maior no Reino é aquele que serve.</p>

        <i>"Quem quiser tornar-se grande entre vós será esse o que vos sirva." (Mateus 20:26)</i>
        <p>Antes de alguém receber um ministério, Deus normalmente trabalha seu coração.</p>

        <ul>
          <li>Moisés passou quarenta anos no deserto.</li>
          <li>José foi escravo e prisioneiro antes de governar o Egito.</li>
          <li>Davi cuidou de ovelhas durante anos antes de assumir o trono.</li>
          <li>Paulo passou um período sendo preparado antes de iniciar suas viagens missionárias.</li>
        </ul>

        <p>Em todos esses exemplos, Deus formou primeiro o homem e depois lhe confiou a missão. Hoje, infelizmente, muitas pessoas desejam subir ao púlpito antes mesmo de aprenderem a servir no banco da igreja.</p>
        <p></p>

        <ul>
          <li>Querem ensinar sem antes aprender.</li>
          <li>Querem liderar sem antes obedecer.</li>
          <li>Querem ser vistos sem antes serem aprovados por Deus.</li>
        </ul>

        <p>O verdadeiro chamado não busca reconhecimento humano. Quem é chamado entende que o ministério traz muito mais responsabilidades do que privilégios. Ser pastor, por exemplo, não significa apenas ocupar um lugar atrás de um púlpito aos domingos.</p>

        <ul>
          <li>Significa visitar quem sofre.</li>
          <li>Significa aconselhar e ensinar.</li>
          <li>Significa corrigir e proteger a igreja.</li>
          <li>Aconselhar famílias.</li>
          <li>Chorar com os que choram.</li>
          <li>Orar pelos enfermos.</li>
          <li>Ensinar a Palavra com fidelidade.</li>
          <li>Corrigir com amor.</li>
          <li>Proteger a igreja dos falsos ensinos.</li>
          <li>Prestar contas a Deus pelas almas que lhe foram confiadas.</li>
        </ul>
        <div class="container-xxl py-4">
          <h6 class="display-8 mb-2">Pedro escreveu aos presbíteros</h6>
          <i>"Apascentai o rebanho de Deus que está entre vós, tendo cuidado dele, não por força, mas voluntariamente; nem por torpe ganância, mas de ânimo pronto; nem como dominadores dos que vos foram confiados, antes tornando-vos modelos do rebanho." (1 Pedro 5:2-3)</i>
        </div>

        <p>Observe que Pedro não descreve um pastor como alguém que manda nas pessoas. Ele descreve alguém que cuida delas.</p>
        <p>O próprio Jesus é o maior exemplo. Ele declarou:</p>

        <i>"Eu sou o bom Pastor; o bom Pastor dá a sua vida pelas ovelhas." (João 10:11)</i>

        <p>Cristo não veio para ser servido, mas para servir (Marcos 10:45). Esse é o padrão para todo líder cristão.</p>

        <p>Quando alguém busca apenas um cargo, normalmente está preocupado com a posição.</p>

        <p>Quando alguém recebe um chamado de Deus, sua preocupação é com as pessoas.</p>

        <ul>
          <li>O primeiro pergunta:</li>
          <li><i>"Qual será o meu título?"</i></li>
          <li>O segundo pergunta:</li>
          <li><i>"Como posso cuidar melhor das almas que Deus colocar em minhas mãos?"</i></li>
        </ul>

        <p>Infelizmente, vemos em muitos lugares pessoas disputando ministérios, cargos e posições como se estivessem concorrendo a uma promoção. Contudo, no Reino de Deus, ministério nunca foi recompensa; sempre foi responsabilidade.</p>

        <p>O Senhor não procura homens que apenas ocupem um púlpito, mas homens que tenham o coração semelhante ao do Bom Pastor.</p>

        <p>Foi por isso que Deus disse sobre Davi:</p>
        <i>"Achei Davi, filho de Jessé, homem segundo o meu coração, que fará toda a minha vontade." (Atos 13:22)</i>

        <li>Antes de olhar para a capacidade, Deus olha para o coração.</li>
        <li>Antes de conceder autoridade, Deus procura fidelidade.</li>
        <li>Antes de entregar um rebanho, Deus observa como alguém cuida das pequenas responsabilidades.</li>

        <p>Jesus ensinou esse princípio ao dizer:</p>
        <i>"Quem é fiel no pouco também é fiel no muito." (Lucas 16:10)</i>

        <p>Portanto, ninguém deve buscar um ministério apenas porque admira o respeito que ele recebe ou o reconhecimento que proporciona. O verdadeiro servo de Deus entende que cada cargo na igreja representa um compromisso diante do Senhor. No dia do juízo, Deus não perguntará quantos títulos alguém acumulou, mas se foi fiel ao chamado que recebeu.</p>

        <p>O ministério não é um palco para exibição pessoal. É um campo de trabalho, onde homens e mulheres são enviados para servir, amar, ensinar e conduzir vidas a Cristo. Quem realmente é chamado por Deus compreende que o maior privilégio não é ser conhecido pelos homens, mas ouvir do Senhor, no fim da caminhada:</p>
        <i>"Muito bem, servo bom e fiel... entra no gozo do teu Senhor." (Mateus 25:21)</i>
