        <h3 class="display-8 mb-4">Um Ministério forjado por Deus</h3>
        <h5 class="display-8 mb-4">Antes de cuidar de pessoas, o homem de Deus precisa aprender a andar com Deus</h5>
        <p><strong>O Caráter e Responsabilidade</strong> dos homens que conduzem o povo de Deus</p>

        <!-- <p> O ministério cristão não é uma posição de prestígio, status ou reconhecimento humano. Na verdade, é uma responsabilidade espiritual extremamente séria, concedida por Deus àqueles que são chamados para cuidar, ensinar, aconselhar e guiar o Seu povo.</p>

        <p>Ao longo das Escrituras, vemos que Deus levanta homens para servir como pastores, presbíteros, anciãos, cooperadores e pregadores da Palavra, homens que se colocam diante da igreja para orientar, corrigir, consolar e fortalecer os irmãos.</p>

        <p>Encontramos esse princípio em diversas passagens da Bíblia. Moisés conduziu Israel no deserto (Êxodo 3:10-12; Deuteronômio 34:9); Josué deu continuidade à liderança do povo (Josué 1:1-9); Samuel julgou e ensinou Israel (1 Samuel 7:15-17); os sacerdotes Esdras e Neemias restauraram a fé e instruíram o povo após o exílio (Esdras 7:10; Neemias 8:8-9).</p> -->


        <p>Existe uma grande diferença entre exercer um cargo e viver um chamado. A Bíblia nunca apresenta o ministério como uma profissão, um título ou uma posição de destaque. Pelo contrário, ela revela que o verdadeiro ministério é resultado de uma vida moldada na presença de Deus.</p>

        <p>Infelizmente, em muitos lugares, a preocupação tem sido formar homens que sabem falar bem, organizar eventos ou administrar uma igreja. Porém, Deus continua procurando homens que, antes de qualquer habilidade, <strong> tenham intimidade com Ele.</strong></p>

        <p>O Senhor nunca escolheu Seus servos apenas pela capacidade intelectual, pela eloquência ou pela influência que possuíam. Em todas as épocas, Deus primeiro trabalhou no coração daqueles que desejava usar.</p>

        <i>"Porque o Senhor não vê como vê o homem. O homem vê a aparência, porém o Senhor olha para o coração."
          (1 Samuel 16:7)</i>

        <p>O ministério começa muito antes do púlpito. Ele começa no quarto de oração, na leitura silenciosa das Escrituras, na luta diária contra o pecado e na disposição de obedecer a Deus quando ninguém está olhando.</p>

        <hr>
        <h5 class="display-8 mb-4">Deus prepara primeiro o homem, depois entrega o rebanho</h5>
        <p>Há uma verdade que percorre toda a Bíblia: Deus nunca entrega grandes responsabilidades a homens que ainda não aprenderam a depender dEle.</p>

        <p>Antes de Moisés conduzir uma nação inteira pelo deserto, Deus permitiu que ele passasse cerca de quarenta anos cuidando de ovelhas em Midiã.</p>
        <p>Aos olhos humanos, parecia perda de tempo.</p>
        <p>Aos olhos de Deus, era treinamento.</p>
        <p>Enquanto Moisés aprendia a conduzir um pequeno rebanho, Deus estava formando nele paciência, humildade, dependência e perseverança.</p>
        <p>Somente depois desse longo processo Deus lhe apareceu na sarça ardente.</p>
        <i>Êxodo 3:1–12</i>
        <p>O mesmo acontece com Davi.</p>
        <p>Antes de governar Israel, ele aprendeu a cuidar das ovelhas de seu pai.</p>
        <p>Foi naquele campo, longe dos aplausos, que Davi conheceu o cuidado de Deus.</p>

        <ul>
          <li>Ali enfrentou o leão.</li>
          <li>Ali enfrentou o urso.</li>
          <li>Ali escreveu muitos salmos.</li>
          <li>Ali aprendeu que o verdadeiro Pastor era o Senhor.</li>
        </ul>
        <i>"O Senhor é o meu pastor; nada me faltará."
          (Salmos 23:1)</i>

        <p>Talvez Davi jamais tivesse escrito o Salmo 23 se nunca tivesse sido um pastor de ovelhas.</p>
        <p>Deus usa os lugares escondidos para formar líderes públicos.</p>
        <hr>
        <h5 class="display-8 mb-4">A comunhão com Deus é a maior ferramenta de um ministro</h5>
        <p>Não existe sermão capaz de substituir uma vida de oração.</p>
        <p>Não existe conhecimento teológico que possa ocupar o lugar da comunhão com Deus.</p>
        <p>Um homem pode conhecer toda a Bíblia de memória e, ainda assim, estar distante do coração de Deus.</p>
        <p>Jesus mostrou isso quando chamou Seus discípulos.</p>
        <p></p>

        <ul>
          <li>Antes de enviá-los para pregar...</li>
          <li>Antes de enviá-los para curar...</li>
          <li>Antes de enviá-los para expulsar demônios...</li>
          <li>Ele os chamou para permanecerem com Ele.</li>
        </ul>
        <i>"Designou doze para estarem com Ele e para os enviar a pregar."
          (Marcos 3:14)</i>

        <ul>
          <li>Observe a ordem.</li>
          <li>Primeiro...</li>
          <li>Estarem com Ele.</li>
          <li>Depois...</li>
          <li>Pregarem.</li>
        </ul>
        <p>O ministério nunca deve substituir a comunhão.</p>

        <p><i>"O ministério não começa com a pregação, mas com a intimidade com Deus."</i></p>
        <p><i>"O ministério não começa com a liderança, mas com a obediência a Deus."</i></p>
        <p><i>"O ministério não começa com a fama, mas com a fidelidade."</i></p>

        <p>Quem deixa de andar com Cristo para trabalhar para Cristo corre o risco de continuar realizando atividades religiosas enquanto seu coração se afasta do Senhor.</p>
        <hr>
        <h5 class="display-8 mb-4">O maior perigo do ministério não é a perseguição</h5>

        <p>Muitos acreditam que o maior inimigo de um ministro seja Satanás, a perseguição ou as dificuldades.</p>

        <p>A Bíblia mostra outro perigo.</p>
        <p>O ativismo sem intimidade.</p>
        <p>É possível ocupar todos os dias da semana com atividades da igreja e, mesmo assim, negligenciar a presença de Deus.</p>
        <p>Jesus advertiu a igreja de Éfeso justamente sobre isso.</p>
        <p>Era uma igreja trabalhadora, perseverante, firme contra falsas doutrinas.</p>
        <p>Mas havia perdido aquilo que sustentava tudo.</p>

        <i>"Tenho, porém, contra ti que abandonaste o teu primeiro amor."
          (Apocalipse 2:4)</i>

        <p>Um ministério pode continuar funcionando externamente enquanto espiritualmente já começou a morrer.</p>
        <p>Por isso, todo homem chamado por Deus precisa vigiar continuamente sua comunhão com o Senhor.</p>
        <hr>
        <h5 class="display-8 mb-4">Quem alimenta o povo precisa primeiro ser alimentado por Deus</h5>

        <p>Nenhum pastor consegue alimentar espiritualmente uma igreja se ele próprio estiver espiritualmente vazio.</p>

        <p>Jeremias declarou:</p>
        <i>"Achadas as tuas palavras, logo as comi; e a tua palavra foi para mim o gozo e a alegria do meu coração."
          (Jeremias 15:16)</i>

        <ul>
          <li>Antes de anunciar a Palavra...</li>
          <li>Jeremias a recebeu.</li>
          <li>Antes de ensinar...</li>
          <li>Ele foi ensinado.</li>
          <li>Antes de falar...</li>
          <li>Ele ouviu.</li>
        </ul>
        <p>Esse princípio continua sendo verdadeiro hoje. Todo ministro precisa ser, antes de tudo, um discípulo constante das Escrituras.</p>

        <hr>
        <h5 class="display-8 mb-4">O pastor deve refletir o coração do Supremo Pastor</h5>

        <p>Jesus não apenas ensinou como um pastor deve agir.</p>
        <p>Ele viveu isso.</p>
        <i>"Eu sou o bom Pastor; o bom Pastor dá a sua vida pelas ovelhas."
          (João 10:11)</i>

        <ul>
          <li>O bom pastor conhece suas ovelhas.</li>
          <li>Ora por elas.</li>
          <li>Chora com elas.</li>
          <li>Alegra-se com elas.</li>
          <li>Ensina.</li>
          <li>Corrige.</li>
          <li>Protege.</li>
        </ul>

        <p>Nunca usa as ovelhas para benefício próprio.</p>
        <p>Antes, entrega sua própria vida em favor delas.</p>
        <p>O verdadeiro ministério não transforma pessoas em instrumentos para crescimento pessoal. Ele se sacrifica para que elas cresçam em Cristo.</p>
        <hr>

        <h5 class="display-8 mb-4">O zelo pelas almas exige responsabilidade</h5>

        <p>Cada pessoa confiada aos cuidados de um líder possui valor eterno.</p>
        <p>Cristo derramou Seu sangue por cada uma delas.</p>
        <p>Por isso, o escritor aos Hebreus faz uma afirmação extremamente séria.</p>
        <i>"Obedecei aos vossos guias... pois velam por vossa alma, como quem deve prestar contas."
          (Hebreus 13:17)</i>
        <p>Todo líder espiritual um dia prestará contas diante de Deus.</p>

        <ul>
          <li>Não apenas pelo que pregou.</li>
          <li>Mas por como viveu.</li>
          <li>Por como tratou as pessoas.</li>
          <li>Por como aconselhou.</li>
          <li>Por como exerceu autoridade.</li>
        </ul>
        <p>Essa verdade deveria produzir temor santo em todo homem que ocupa um ministério.</p>

        <hr>

        <h5 class="display-8 mb-4">O Espírito Santo continua sendo o verdadeiro Pastor da Igreja</h5>

        <p>Nenhum homem é dono da Igreja.</p>
        <p>A Igreja pertence a Cristo.</p>
        <p>O Espírito Santo continua dirigindo Seu povo.</p>
        <p>Quando Paulo se despediu dos presbíteros de Éfeso, ele fez uma observação extraordinária.</p>

        <i>"Olhai por vós e por todo o rebanho sobre o qual o Espírito Santo vos constituiu bispos."
          (Atos 20:28)</i>

        <ul>
          <li>Não foi uma eleição humana.</li>
          <li>Não foi um título.</li>
          <li>Não foi influência.</li>
        </ul>

        <p>Foi o Espírito Santo quem os colocou naquela função. Da mesma forma, somente o Espírito Santo pode sustentar um verdadeiro ministério.</p>

        <hr>
        <h5 class="display-8 mb-4">Um ministério sem santidade perde sua autoridade espiritual</h5>

        <p>O ministério não é apenas uma função, mas um estilo de vida.</p>
        <p>A autoridade do homem de Deus não está em sua voz.</p>

        <p>Nem em seu cargo.</p>
        <p>Nem em sua fama.</p>
        <p>Sua autoridade nasce da sua vida diante de Deus.</p>
        <p>Paulo escreveu:</p>

        <i>"Tem cuidado de ti mesmo e da doutrina; persevera nestas coisas."
          (1 Timóteo 4:16)</i>

        <ul>
          <li>Observe a ordem novamente.</li>
          <li>Primeiro...</li>
          <li>Cuida de ti mesmo.</li>
          <li>Depois...</li>
          <li>Da doutrina.</li>
        </ul>
        <p>O homem que não vigia sua própria vida jamais conseguirá cuidar corretamente da vida espiritual de outras pessoas.</p>
        <hr>
        <h5 class="display-8 mb-4">Deus continua formando homens escondidos</h5>

        <p>Vivemos em uma geração fascinada por visibilidade.</p>
        <p>Mas Deus continua formando Seus servos longe dos holofotes.</p>

        <ul>
          <li>Foi assim com José na prisão.</li>
          <li>Foi assim com Davi nos campos.</li>
          <li>Foi assim com Elias junto ao ribeiro de Querite.</li>
          <li>Foi assim com João Batista no deserto.</li>
          <li>Foi assim com Paulo durante anos de preparo antes de iniciar suas viagens missionárias.</li>
          <li>Antes de Deus revelar um homem ao público...</li>
          <li>Normalmente o forma no secreto.</li>
        </ul>

        <p>Porque a intimidade construída no anonimato sustenta a fidelidade quando chegam a influência, o reconhecimento e a responsabilidade.</p>
        <i>"Teu Pai, que vê em secreto, te recompensará."
          (Mateus 6:6)</i>

        <hr>
        <h5 class="display-8 mb-4">Um ministério forjado por Deus nunca deixa de depender de Deus</h5>
        <p>O maior sinal de maturidade espiritual não é o tempo de ministério.</p>
        <p>Não é a quantidade de sermões pregados.</p>
        <p>Não é o número de pessoas lideradas.</p>
        <p>É permanecer dependente de Deus mesmo depois de muitos anos caminhando com Ele.</p>
        <p>Quanto mais um homem conhece a Deus, mais percebe o quanto precisa da Sua graça.</p>
        <p>Foi por isso que Jesus declarou:</p>
        <i>"Sem mim nada podeis fazer."
          (João 15:5)</i>

        <p>Essa talvez seja a maior lição de um ministério forjado por Deus.</p>
        <p>O verdadeiro líder espiritual nunca acredita que chegou ao ponto de não precisar mais aprender, orar ou buscar ao Senhor.</p>
        <p>Ele compreende que sua força não está em sua experiência, mas na presença constante de Deus.</p>
        <p>E somente um homem que continua sendo diariamente pastoreado pelo Supremo Pastor será capaz de pastorear o rebanho que Cristo comprou com Seu precioso sangue.</p>

        <i>"E, quando se manifestar o Supremo Pastor, recebereis a imarcescível coroa da glória."
          (1 Pedro 5:4)</i>

        <i>“Apascentai o rebanho de Deus que está entre vós.”
          (1 Pedro 5:2)</i>

