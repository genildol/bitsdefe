      <h2 class="display-8 mb-4">Pregue a Palavra: A autoridade da pregação está na Escritura, não na experiência pessoal</h2>
      <p>A pregação cristã verdadeira tem sua base exclusiva na Palavra de Deus, e não em opiniões humanas, sentimentos ou experiências pessoais. A Escritura é a revelação final e suficiente da vontade de Deus para a fé e a prática. O apóstolo Paulo exorta claramente: “Prega a Palavra, insta a tempo e fora de tempo” (2 Timóteo 4:2). Isso deixa evidente que o conteúdo da pregação deve ser a Palavra revelada, e não ideias pessoais adaptadas ao gosto do público.</p>

      <p>A autoridade do pregador não está em sua história de vida, em seus testemunhos ou em sua eloquência, mas no texto bíblico corretamente interpretado. A Bíblia afirma que “toda a Escritura é divinamente inspirada e proveitosa para ensinar, repreender, corrigir e instruir em justiça” (2 Timóteo 3:16). Quando a pregação se afasta da Escritura, ela perde sua autoridade espiritual, tornando-se apenas discurso humano.</p>

      <p>Experiências pessoais podem até ilustrar verdades bíblicas, mas jamais substituí-las. A fé cristã não é edificada sobre relatos subjetivos, mas sobre a verdade objetiva da Palavra de Deus. Paulo deixa isso claro ao afirmar que “a fé vem pelo ouvir, e o ouvir pela Palavra de Deus” (Romanos 10:17). Não é a experiência que gera fé, mas a exposição fiel das Escrituras.</p>

      <p>Quando a pregação se baseia em opiniões, ela se torna instável e vulnerável ao erro. A Bíblia adverte que chegará um tempo em que as pessoas não suportarão a sã doutrina, buscando mestres segundo seus próprios desejos (2 Timóteo 4:3). Por isso, o pregador fiel deve permanecer firme na Palavra, mesmo quando ela confronta, corrige e incomoda.</p>

      <p>A Escritura também alerta contra o perigo de adicionar ou retirar algo da mensagem revelada. Deus declara: “Nada acrescentareis à palavra que vos mando, nem diminuireis dela” (Deuteronômio 4:2). A pregação que mistura a Palavra com opiniões humanas corre o risco de distorcer o evangelho e conduzir pessoas ao erro espiritual.</p>

      <p>Jesus é o maior exemplo de uma pregação fundamentada na Escritura. Em diversas ocasiões, Ele afirmou: “Está escrito” (Mateus 4:4, 7, 10), demonstrando que até o Filho de Deus submeteu Seus ensinamentos à autoridade da Palavra. Isso nos ensina que nenhuma experiência pessoal está acima da revelação bíblica.</p>

      <p>A igreja é chamada a permanecer firme na doutrina apostólica, que tem como fundamento a Palavra de Deus. A Bíblia afirma que a igreja está edificada “sobre o fundamento dos apóstolos e dos profetas, de que Jesus Cristo é a principal pedra da esquina” (Efésios 2:20). Esse fundamento não é experiência, mas revelação divina registrada nas Escrituras.</p>

      <p>Portanto, pregar a Palavra é um compromisso de fidelidade a Deus e à verdade. A autoridade da pregação não vem do homem, mas da Escritura inspirada. Como diz o profeta Isaías: “Seca-se a erva, e cai a flor, porém a palavra de nosso Deus subsiste eternamente” (Isaías 40:8). Toda pregação que deseja permanecer firme e frutífera deve estar totalmente submissa à Palavra de Deus.</p>

