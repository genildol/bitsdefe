      <h2 class="display-8 mb-4">Quando tudo terminar, o que terá valido a pena?</h2>

      <p>Quando a vida chega ao fim, as perguntas mais importantes não giram em torno de quanto dinheiro foi acumulado, mas se a vida teve propósito. A Bíblia nos lembra que as riquezas são passageiras, mas aquilo que é feito com sabedoria e amor permanece.</p>

      <p><i>“Porque que aproveita ao homem ganhar o mundo inteiro e perder a sua alma?”
          (Marcos 8:36)</i></p>

      <p>No final, ninguém será lembrado pelos bens que possuiu, mas pelo amor que demonstrou; não pelos títulos que conquistou, mas pelas vidas que tocou. O verdadeiro valor da vida está nas conexões que construímos, no impacto que deixamos e na forma como refletimos o caráter de Cristo.</p>

      <p><i> “Agora, pois, permanecem a fé, a esperança e o amor; porém o maior destes é o amor.” (1 Coríntios 13:13)</i></p>

      <p>O legado mais significativo não se mede em posses, mas em gestos de bondade, compaixão e fidelidade a Deus. Tudo o que construímos e conquistamos deve ser vivido de forma consciente, com gratidão e responsabilidade, e não de maneira vazia ou egoísta.</p>

      <p><i>“Ensina-nos a contar os nossos dias, para que alcancemos coração sábio.” (Salmos 90:12)</i></p>

      <p> A Palavra de Deus nos orienta a viver com intenção, buscando a sabedoria divina para fazer escolhas que realmente importam. Uma vida guiada por Deus reflete amor, produz frutos e deixa um testemunho duradouro.</p>

      <p><i>“Tudo quanto fizerdes, fazei-o de todo o coração, como para o Senhor.” (Colossenses 3:23)</i></p>

      <p>Ter bens, conquistas e progresso não é errado. O erro está em permitir que isso nos afaste das pessoas e nos torne indiferentes ao próximo. Desprezar relacionamentos por causa de coisas passageiras empobrece a alma.</p>

      <p><i>“Não ajunteis tesouros na terra… mas ajuntai tesouros no céu.” (Mateus 6:19–20)</i></p>

      <p>No fim, o que realmente importa é viver com propósito, amar de verdade e deixar um legado que glorifique a Deus.</p>
      <p> <strong> E agora fica a pergunta: o que realmente importa para você?</strong></p>

