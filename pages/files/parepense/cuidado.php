      <h2 class="display-8 mb-4">Cuidado, não se acostume a está vazio</h2>

      <h5 class="display-8 mb-4">Quando a falta de conhecimento da Palavra se torna um modo de vida</h5>

      <p>Existe um tipo de vazio que deveria nos incomodar.</p>
      <p>É aquele vazio de quem frequenta uma igreja, conhece cânticos, costumes, expressões religiosas e até possui muitos anos de caminhada cristã, mas quando precisa compreender aquilo em que crê, encontra dificuldade para explicar.</p>
      <p>Sabe que "Jesus salva", mas talvez não saiba explicar o que significa salvação.</p>
      <p>Sabe que "Cristo morreu por nós", mas talvez não compreenda o significado da cruz.</p>
      <p>Sabe que devemos ter fé, mas talvez nunca tenha parado para entender biblicamente o que é fé.</p>
      <p>Sabe que devemos ter fé, mas talvez nunca tenha parado para entender biblicamente o que é fé.</p>
      <p>Sabe que existe graça, mas talvez ainda viva como se precisasse conquistar diante de Deus aquilo que Cristo já realizou.</p>
      <p>Sabe muitas coisas sobre a religião, mas conhece pouco o Evangelho.</p>
      <p>E existe um perigo ainda maior: <strong>acostumar-se com esse vazio.</strong></p>

      <p>Quando uma pessoa passa muito tempo sem conhecer a Palavra, ela pode deixar de perceber que está vazia. O pouco começa a parecer suficiente. O costume passa a substituir o conhecimento. A tradição passa a substituir a investigação. A opinião de outras pessoas passa a substituir as Escrituras.</p>

      <p>E assim, sem perceber, alguém pode passar anos dentro da vida religiosa sem realmente amadurecer no conhecimento de Cristo.</p>

      <h5 class="display-8 mb-4">O vazio espiritual nem sempre parece vazio</h5>
      <p>Quando pensamos em alguém vazio espiritualmente, talvez imaginemos uma pessoa que abandonou completamente a fé. </p>
      <p>Mas nem sempre é assim. </p>
      <p>Existe um vazio que pode estar escondido dentro de uma vida aparentemente religiosa. </p>
      <p>Jesus advertiu sobre pessoas que honravam a Deus externamente, mas cujo coração estava distante: </p>
      <p><i>"Este povo honra-me com os lábios, mas o seu coração está longe de mim."
          Mateus 15:8</i></p>
      <p>Isso nos ensina algo importante: </p>
      <p><strong>Aparência religiosa não é a mesma coisa que relacionamento com Deus.</strong> </p>
      <p>Uma pessoa pode estar presente fisicamente e ausente espiritualmente.</p>
      <p>Pode conhecer a rotina e desconhecer o propósito.</p>
      <p>Pode conhecer os costumes e desconhecer as Escrituras.</p>
      <p>Pode saber o que sua igreja ensina e nunca ter examinado cuidadosamente aquilo que a Bíblia ensina.</p>
      <p>Pode até defender determinadas doutrinas com grande convicção, mas sem jamais ter estudado suficientemente a base bíblica delas.</p>
      <p>Por isso, precisamos tomar cuidado.</p>
      <p><strong>Não devemos medir nossa maturidade espiritual apenas pelo tempo que estamos na igreja, pela quantidade de cultos que frequentamos ou pela quantidade de coisas religiosas que aprendemos.</strong></p>
      <p>A pergunta também precisa ser:</p>
      <p><strong>Quanto eu conheço verdadeiramente a Palavra de Deus?</strong></p>

      <h5 class="display-8 mb-4">O perigo de crescer dentro de uma cultura religiosa</h5>

      <p>Muitas pessoas aprendem a fé desde pequenas.</p>
      <p>Isso pode ser uma benção, mas também pode ser um perigo se não houver um crescimento real na compreensão e no relacionamento com Deus.</p>
      <p>Ela aprende:</p>
      <p>"É assim porque sempre foi assim."</p>
      <p>"Na nossa igreja é desse jeito."</p>
      <p>"Foi assim que me ensinaram."</p>
      <p>"Não precisamos questionar."</p>
      <p>Mas existe uma diferença enorme entre questionar para destruir a fé e examinar para fortalecê-la.</p>
      <p>A Bíblia não apresenta a ignorância espiritual como virtude.</p>
      <p>Pelo contrário:</p>
      <p><i>"Examinai tudo. Retende o bem." 1 Tessalonicenses 5:21</i></p>
      <p>Os cristãos de Bereia receberam uma recomendação justamente porque examinavam aquilo que ouviam:</p>
      <p><i>"Examinando cada dia nas Escrituras se estas coisas eram assim." Atos 17:11</i></p>
      <p>Eles não aceitaram simplesmente porque alguém havia falado.</p>
      <p>Eles foram às Escrituras.</p>
      <p>Isso é muito importante para o cristão.</p>
      <p><i>Nossa fé não deveria depender apenas daquilo que alguém nos ensinou sobre a Bíblia. Precisamos aprender a conhecer a própria Bíblia.</i></p>

      <h5 class="display-8 mb-4">Existe uma diferença entre conhecer a religião e conhecer a Cristo</h5>
      <p>Uma das maiores confusões que podem existir na vida cristã é confundir <strong>religiosidade com conhecimento de Cristo.</strong> </p>

      <ul>
        <li>o que vestir;</li>
        <li>como falar;</li>
        <li>como se comportar;</li>
        <li>onde ir;</li>
        <li>onde não ir;</li>
        <li>quais costumes seguir;</li>
        <li>quais tradições manter;</li>
      </ul>
      <p>Tudo isso pode ocupar espaço dentro de uma comunidade. Mas o Evangelho vai muito mais produdamente</p>
      <p>Ele pergunta:</p>
      <ul>
        <li>Você conhece a Cristo?</li>
        <li>Você compreende o que Ele fez por você?</li>
        <li>Você entende o que significa ser salvo?</li>
        <li>Você sabe o que significa ser transformado pelo Evangelho?</li>
        <li>O que Cristo realizou?</li>
        <li>O que significa ser justificado pela fé?</li>
        <li>O que é graça</li>
        <li>O que significa arrependimento?</li>
        <li>O que aconteceu com o homem por causa do pecado?</li>
        <li>O que Deus fez para reconciliar o pecador consigo</li>
        <li>O que significa nascer de novo?</li>
        <li>O que significa viver em Cristo?</li>
        <li>Qual é a identidade daquel que foi alcancado pelo Evangelho?</li>
      </ul>

      <p>Essas perguntas não são detalhes.</p>
      <p> <strong>Elas estão no centro da fé cristã.</strong></p>
      <p>Paulo expressou seu desejo de conhecer cada vez mais profundamente a Cristo:</p>
      <p><i>"Para conhecê-lo, e à virtude da sua ressurreição, e à comunicação de suas aflições." Filipenses 3:10</i></p>
      <p>Se Paulo, um dos grandes apóstolos do Novo Testamento, ainda desejava conhecê-lo mais, como podemos imaginar que já sabemos tudo o que precisamos saber?</p>

      <h5 class="display-8 mb-4">O cristão precisa crescer no conhecimento</h5>

      <p>A vida cristã não deveria permanecer eternamente no mesmo nível. Paulo escreveu:</p>
      <p><i>"Crescei na graça e conhecimento de nosso Senhor e Salvador, Jesus Cristo." 2 Pedro 3:18</i></p>
      <p>Observe duas coisas colocadas juntas:</p>
      <p><strong>Graça</strong> e <strong>Conhecimento</strong></p>
      <p>O cristão precisa crescer na graça, mas também precisa crescer no conhecimento.</p>
      <p>O conhecimento não é apenas intelectual. Ele envolve compreender a Palavra, mas também envolve compreender a Cristo, compreender o Evangelho e compreender a vida cristã.</p>

      <ul>
        <li>O cristão precisa crescer.</li>
        <li>Não apenas crescer em idade.</li>
        <li>Não apenas crescer em tempo de igreja.</li>
        <li>Não apenas crescer em responsabilidades.</li>
        <li>Mas crescer na <strong> graça e no conhecimento de Jesus Cristo.</strong></li>
      </ul>
      <p>Uma pessoa pode ter vinte anos de igreja e continuar espiritualmente infantil se nunca desenvolveu conhecimento, discernimento e maturidade.</p>
      <p>O autor de Hebreus demonstra preocupação justamente com isso:</p>
      <p><i>"Porque, devendo já ser mestres pelo tempo, ainda necessitais de que se vos torne a ensinar quais sejam os primeiros rudimentos das palavras de Deus." Hebreus 5:12</i></p>
      <p>O problema não era falta de tempo.</p>
      <p>Era falta de crescimento proporcional ao tempo.</p>
      <p>Isso deveria nos fazer refletir.</p>
      <p>Quanto tempo passou desde que começamos a seguir a Cristo? E quanto realmente crescemos no conhecimento dele?</p>

      <h5 class="display-8 mb-4">O problema de depender sempre de alguém para conhecer a Bíblia</h5>
      <p>É importante termos pastores, professores, líderes e irmãos que nos ensinem. Deus concedeu dons e ministérios para edificação da Igreja. Mas existe uma diferença entre receber ensino e ser eternamente dependente de alguém para descobrir o que a Bíblia diz. O cristão precisa desenvolver capacidade de estudar, compreender, comparar e discernir.</p>
      <ul>
        <li>Não significa que todos serão teólogos.</li>
        <li>Não significa que todos terão a mesma capacidade intelectual.</li>
        <li>Não significa que todos interpretarão cada passagem da mesma maneira.</li>
        <li>Significa simplesmente que:</li>
        <li><strong>Todo cristão deveria desenvolver um relacionamento sério com a Palavra de Deus.</strong></li>
      </ul>
      <p>Jesus Cristo disse:</p>
      <p><i>"Errais, não conhecendo as Escrituras, nem o poder de Deus." Mateus 22:29</i></p>
      <p>Perceba a gravidade dessas palavras.</p>
      <p>É possível errar justamente por não conhecer as Escrituras.</p>
      <p>Portanto, ignorância bíblica não é algo que devemos celebrar.</p>

      <h5 class="display-8 mb-4">Quando o pouco conhecimento passa parecer suficiente</h5>
      <p>Existe um perigo silencioso:</p>
      <p><i>o pouco pode parecer muito quando nunca conhecemos a profundidade do que existe.</i></p>
      <p>Quem nunca estudou determinado assunto pode imaginar que já sabe bastante.</p>
      <p>Isso também pode acontecer com a fé.</p>
      <ul>
        <li>A pessoa conhece algumas histórias bíblicas.</li>
        <li>Conhece alguns versículos.</li>
        <li>Conhece alguns hinos.</li>
        <li>Conhece algumas doutrinas.</li>
        <li>Conhece alguns costumes.</li>
      </ul>
      <p>E pensa:</p>
      <p>"Eu já conheço a bíblia."</p>
      <p>Mas a Bíblia é muito maior do que algumas histórias conhecidas.</p>
      <ul>
        <li>É muito maior do que versículos isolados.</li>
        <li>É muito maior do que frases religiosas.</li>
        <li>É muito maior do que aquilo que ouvimos durante anos.</li>
      </ul>
      <p>A Palavra de Deus apresenta uma história de redenção que encontra seu centro em Cristo.</p>
      <p>Jesus Cristo disse:</p>
      <p><i>"Examinais as Escrituras, porque vós cuidais ter nelas a vida eterna, e são elas que de mim testificam."
          João 5:39</i></p>
      <p>Conhecer a Bíblia é fundamental para o crescimento espiritual e isto nos conduz a Cristo.</p>

      <h5 class="display-8 mb-4">Não conhecer a graça pode produzir uam vida pesada</h5>
      <p>Talvez uma das maiores consequências da falta de conhecimento bíblico seja não compreender corretamente a graça. Muitas pessoas vivem uam espécie de cristianismo baseado constantemente no medo de não serem suficientes.</p>
      <p>Fazem algo para tentar merecer Deus ou deixam de fazer com medo de uma "punição".</p>
      <p>Cumprem algo para tentar comprar aprovação.</p>
      <p>Evitam determinadas coisas pensando que, por isso, conseguirão conquistar a salvação.</p>
      <p>Vivem tentando construir uma justiça própria. <a href="index.php?page=">Entenda a graça</a> </p>
      <p>Mas o Evangelho apresenta outra realidade.</p>
      <p><i>"Porque pela graça sois salvos, por meio da fé; e isto não vem de vós; é dom de Deus." Efésios 2:8</i></p>

      <p>A salvação não é um prêmio que o homem consegue acumular por seus próprios méritos.</p>
      <p>É graça.</p>
      <p>Cristo realizou aquilo que nós não poderíamos realizar sozinhos. Paulo continua:</p>
      <p><i>"Não vem das obras, para que ninguém se glorie." Efésios 2:9</i></p>
      <p>Isso não significa que as obras sejam inúteis, mas sim que elas não são o meio de salvação. O prórpio texto continua dizendo:</p>
      <p><i>"Porque somos feitura sua, criados em Cristo Jesus, para as boas obras, que Deus preparou, a fim de que andemos nelas." Efésios 2:10</i></p>

      <p>Existe uma ordem fundamental. <i>Não somos salvos peloas obras; somos salvos pela graça para uma vida de boas obras.</i></p>
      <p>Essa compensasão muda completamente a maneira de enxergar a vida e a relação com Deus.</p>

      <h5 class="display-8 mb-4">O que Cristo nos deu pela graça?</h5>
      <p>Quando o cristão não conhece profundamente o Evangelho, pode viver sem compreender a grandeza daquilo que recebeu.

        Em Cristo existe justificação:</p>
      <p><i>"Sendo justificados gratuitamente pela sua graça, pela redenção que há em Cristo Jesus."
          Romanos 3:24</i></p>

      <p>Existe reconciliação com Deus:</p>
      <p><i>"Deus estava em Cristo reconciliando consigo o mundo."
          2 Coríntios 5:19</i></p>

      <p>Existe uma nova vida:</p>
      <p><i>"Assim que, se alguém está em Cristo, nova criatura é."
          2 Coríntios 5:17</i></p>

      <p>Existe adoção:</p>
      <p><i>"Mas, a todos quantos o receberam, deu-lhes o poder de serem feitos filhos de Deus."
          João 1:12</i></p>

      <p>Existe liberdade da condenação:</p>
      <p><i>"Portanto, agora nenhuma condenação há para os que estão em Cristo Jesus."
          Romanos 8:1</i></p>

      <p>Existe esperança:</p>
      <p><i>"Bendito o Deus e Pai de nosso Senhor Jesus Cristo, que, segundo a sua grande misericórdia, nos gerou de novo para uma viva esperança."
          1 Pedro 1:3</i></p>

      <p>Perceba a dimensão disso.</p>
      <p><strong>Como alguém pode conhecer essas verdades e permanecer espiritualmente indiferente?</strong></p>
      <p>Talvez porque nunca tenha sido ensinado a compreender profundamente o Evangelho e isso o torna insensível às coisas do Espírito.</p>

      <h5 class="display-8 mb-4">A graça não produz vazio; produz transformação</h5>
      <p>Também precisamos tomar cuidado com outro erro. Compreender a graça não significa dizer:</p>
      <p>"Então não importa como eu vivo."</p>
      <p>A graça não é uma licença para viver sem propósito, mas sim um poder que transforma a vida, não é uma autorização para permanecer no pecado. Paulo pergunta:</p>
      <p><i>"Permaneceremos no pecado, para que a graça abunde?" Romanos 6:1</i></p>

      <p>E responde:</p>
      <p><i>"De modo algum."</i></p>
      <p>A graça que salva também transforma.

        O verdadeiro conhecimento de Cristo não produz apenas informação.

        Produz mudança.</p>

      <p>Conhecer a Cristo deve afetar:</p>

      <ul>
        <li>Nossa maneira de pensar;</li>
        <li>Nossa maneira de tratar as pessoas;</li>
        <li>Nossa maneira de lidar com o pecado;</li>
        <li>Nossa maneira de servir;</li>
        <li>Nossa maneira de relacionar-nos com os outros;</li>
        <li>Nossa maneira de ver o mundo;</li>
        <li>Nossa maneira de trabalhar;</li>
        <li>Nossa maneira de lidar com o dinheiro;</li>
        <li>Nossa maneira de enfrentar dificuldades;</li>
        <li>Nossa maneira de perdoar;</li>
        <li>Nossa maneira de enxergar a própria vida.</li>
      </ul>
      <p><strong>O conhecimento bíblico que não transforma nada precisa ser novamente examinado</strong></p>

      <h5 class="display-8 mb-4">O cristão não foi chamado para permanecerno vazio</h5>
      <p>Jesus Cristo declarou:</p>
      <p><i>"Eu vim para que tenham vida, e a tenham com abundância."
          João 10:10</i></p>

      <p>Isso não significa uma promessa de uma vida sem problemas, sofrimento ou dificuldades.

        Significa que a vida encontrada em Cristo não é uma existência sem propósito.

        O cristão recebeu uma nova perspectiva.</p>

      <ul>
        <li>Existe propósito</li>
        <li>Existe esperança</li>
        <li>Existe reconciliação</li>
        <li>Existe uma missão</li>
        <li>Existe uma comunidade</li>
        <li>Existe crescimento.</li>
        <li>Existe serviço</li>
        <li>Existe santificação.</li>
        <li>Existe Cristo.</li>
      </ul>
      <p>Por isso, é necessário perguntar:</p>
      <p><strong>Por que estamos nos contentando com tão pouco?</strong></p>

      <h5 class="display-8 mb-4">Não se acostume a estar vazio</h5>

      <p>Talvez esta seja a principal advertência deste estudo. Se você percebe que conhece pouco a Bíblia, não se acostume com isso. Se não consegue explicar aquilo em que acredita, se conhece mais tradições do que Escrituras ou se simplesmente repete ensinamentos que nunca examinou biblicamente, não considere essa situação normal. O vazio espiritual não deve ser aceito como uma característica natural da vida cristã; ele deve despertar em nós fome e desejo de conhecer mais a Deus.</p>

      <p><i>Jesus disse: "Bem-aventurados os que têm fome e sede de justiça, porque eles serão fartos." Mateus 5:6. </i></p>

      <p>Aquele que reconhece que está vazio não precisa permanecer assim. Existe a Palavra de Deus, existe o Evangelho, existe a graça e, acima de tudo, existe Cristo. O problema não é perceber que estamos vazios; o problema é perceber e decidir permanecer assim.</p>

      <h5 class="display-8 mb-4">Comece a estudar</h5>

      <p>Não é necessário começar tentando compreender toda a Bíblia de uma só vez. Comece por Cristo. Leia os Evangelhos, observe seus ensinamentos, sua maneira de tratar as pessoas, sua relação com o Pai e aquilo que ensinou sobre pecado, arrependimento, fé, graça e o Reino de Deus. Depois, avance para as cartas e procure compreender o que os apóstolos ensinaram sobre a obra de Cristo e a vida cristã.</p>

      <p>Ao estudar, procure compreender o contexto das passagens, quem escreveu, para quem escreveu, qual era a situação envolvida e como aquele texto se relaciona com o restante das Escrituras. Não construa uma doutrina inteira sobre um versículo isolado. Pergunte sempre: o que este texto realmente ensina sobre Deus, sobre o pecado, sobre Cristo e sobre a vida que Deus deseja para seu povo? Estudar a Bíblia não é apenas acumular informações, mas permitir que a Palavra molde nossa compreensão da fé.</p>

      <h5 class="display-8 mb-4">Conhecimento não é orgulho</h5>

      <p>Estudar a Bíblia não deve produzir arrogância. Quanto mais conhecemos verdadeiramente a Deus, mais percebemos o quanto ainda temos para aprender. Paulo escreveu: </p>
      <p><i>"Se alguém cuida saber alguma coisa, ainda não sabe como convém saber." 1 Coríntios 8:2.</i></p>

      <p>O objetivo do conhecimento bíblico não é permitir que alguém diga "eu sei mais do que você", mas conduzir-nos a uma atitude de humildade e desejo contínuo de conhecer a Cristo. O verdadeiro conhecimento das Escrituras deve produzir discernimento, maturidade, amor e transformação. Quanto mais aprendemos, mais devemos reconhecer nossa dependência de Deus e nossa necessidade de continuar aprendendo.</p>

      <h5 class="display-8 mb-4">Uma pergunta que precisamos fazer</h5>

      <p>Talvez a pergunta mais importante deste estudo não seja quanto tempo estamos na igreja, quantos versículos conhecemos ou quantos cultos frequentamos. A pergunta é:</p>

      <p><i>"Você conhece verdadeiramente aquilo em que diz acreditar?"</i></p>

      <p>Se alguém perguntar por que você é cristão, o que é o Evangelho, o que significa ser salvo pela graça, por que Cristo morreu ou o que mudou em sua vida por causa dele, você saberia responder biblicamente? Essas perguntas não foram feitas para produzir vergonha ou condenação, mas para despertar em nós o desejo de conhecer mais profundamente a fé que professamos. Afinal, não deveríamos apenas dizer que somos cristãos; deveríamos procurar compreender o que significa ser cristão.</p>

      <h5 class="display-8 mb-4">Não tenha medo de descobrir que você sabe pouco</h5>
      <p>Descobrir que sabemos pouco não é uma derrota; pode ser o começo de uma grande jornada. O verdadeiro problema não está em reconhecer "eu ainda preciso aprender", mas em acreditar que não precisamos aprender mais. A primeira atitude demonstra humildade; a segunda pode revelar acomodação.</p>

      <p>Por isso, se você percebe que sua vida cristã está carente de conhecimento, não desista nem tenha vergonha de começar. <strong> Abra a Bíblia, leia, estude, pergunte, compare, ore e procure compreender.</strong> Permita também que a Palavra confronte aquilo que você aprendeu ao longo da vida, inclusive aquilo que acreditava conhecer. Nossa fidelidade não deve estar primeiramente em uma tradição, cultura ou costume, mas em Cristo e na verdade revelada nas Escrituras.</p>

      <h5 class="display-8 mb-4">Conclusão: Não se acostume com o vazio</h5>
      <p>Talvez você tenha passado anos dentro da igreja e ainda tenha muitas perguntas. Talvez tenha aprendido mais costumes do que doutrina, mais a participar do que a compreender, ou tenha recebido muitas respostas prontas e poucas oportunidades para estudar. Isso não precisa ser o fim da história. Reconhecer que precisamos aprender não é sinal de fraqueza, mas pode ser o primeiro passo para uma fé mais consciente, madura e fundamentada na Palavra de Deus.</p>

      <p>Não se acostume com o vazio. Não confunda tradição com Escritura, religiosidade com transformação ou informação religiosa com conhecimento de Cristo. Há muito mais para conhecer, compreender e viver. O Evangelho é a boa notícia daquilo que Deus realizou em Cristo por nós, mediante sua graça. Por isso, a pergunta que fica para cada um de nós é: você está realmente crescendo no conhecimento de Cristo ou simplesmente se acostumou com o vazio?</p>

      Como escreveu Pedro:

      <p><i>"Crescei na graça e conhecimento de nosso Senhor e Salvador, Jesus Cristo." 2 Pedro 3:18.</i></p>

