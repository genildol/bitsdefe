            <h1>Confissão de Fé</h1>
            <h5 class="mb-3">O que é uma Confissão de Fé?</h5>

            <p class="mb-3">"Uma Confissão de Fé é uma declaração organizada e fundamentada das principais crenças doutrinárias de uma pessoa, igreja ou movimento cristão. Ela tem como objetivo afirmar <strong> aquilo que se crê, por que se crê e em que base bíblica essa crença está fundamentada.</strong></p>

            <p>Em outras palavras, uma confissão de fé é como uma declaração de identidade espiritual.</p>
            <p>Ela responde perguntas como:</p>
            <ul>
              <li>Quem é Deus?</li>
              <li>Quem é Jesus Cristo?</li>
              <li>Quem é o Espírito Santo?</li>
              <li>O que a Bíblia ensina?</li>
              <li>Qual é a condição do ser humano?</li>
              <li>Como ocorre a salvação?</li>
              <li>O que é a Igreja?</li>
              <li>Qual é a missão do cristão?</li>
              <li>O que acontecerá no fim dos tempos?</li>
            </ul>

            <h5 class="mb-3">O significado de "confessar a fé"</h5>
            <p>A confissão de fé é uma declaração pública de crenças e convicções religiosas. É uma forma de expressar a fé e a identidade cristã. A palavra "confissão" vem do conceito bíblico de declarar publicamente aquilo que se acredita.</p>

            <p>A Bíblia diz:</p>

            <p> <i>"Confessa-te diante de Deus, e não te escondas de Cristo."</i></p>
            <p> <i>"Porque com o coração se crê para a justiça, e com a boca se faz confissão para a salvação." Romanos 10:10</i></p>

            <p>Confessar a fé não é apenas dizer que acredita em algo, mas assumir publicamente uma verdade e viver de acordo com ela.</p>

            <p>Quando um cristão declara:</p>
            <i>"Eu creio em Deus Pai, em Jesus Cristo como Salvador e na autoridade das Escrituras",</i>
            <p>Ele está fazendo uma confissão de fé.</p>
            <hr>

            <h5 class="mb-3">Diferença entre Credo e Confissão de Fé</h5>
            <p>Existe uma diferença importante.</p>
            <h5 class="mb-3">Credo</h5>
            <p>Um credo normalmente é uma declaração curta e resumida. Exemplo:</p>

            <p><i>"Creio em Deus Pai Todo-Poderoso, Criador do céu e da terra; e em Jesus Cristo, seu único Filho, nosso Senhor..."</i></p>

            <h5 class="mb-3">Confissão de Fé</h5>

            <p>Uma confissão de fé é mais detalhada. Ela não apenas resume as crenças, mas também as explica e fundamenta.</p>

            <p>Ela não apenas diz:</p>
            <i>"Creio na Bíblia"</i>
            <p>Ela explica:</p>

            <i>"Cremos que as Sagradas Escrituras são inspiradas por Deus, constituem a autoridade suprema para fé e prática, foram produzidas pelo Espírito Santo através de homens escolhidos e permanecem como regra infalível para conduzir o povo de Deus."</i>

            <p>Ou seja:</p>
            <p>O credo declara.</p>
            <p>A confissão de fé explica e fundamenta.</p>

            <hr>

            <h5 class="mb-3">Exemplos históricos de Confissões de Fé</h5>
            <p>Ao longo da história cristã, várias comunidades produziram confissões para registrar suas convicções.</p>
            <p>Alguns exemplos:</p>
            <p>Confissão de Westminster (1646)</p>
            <p>Uma das confissões mais conhecidas da tradição reformada.</p>
            <p>Ela trata de temas como:</p>
            <ul>
              <li>Escrituras;</li>
              <li>Deus;</li>
              <li>Trindade;</li>
              <li>Criação;</li>
              <li>Providência;</li>
              <li>Cristo;</li>
              <li>Justificação;</li>
              <li>Igreja;</li>
              <li>Juízo Final.</li>
            </ul>
            <p>Entre outras:</p>

            <h6 class="mb-3">Confissão de Fé de Londres (1689)</h6>
            <p>Uma declaração doutrinária produzida por igrejas batistas históricas.</p>
            <ul>
              <li>Autoridade da Bíblia;</li>
              <li>Natureza de Deus;</li>
              <li>Salvação;</li>
              <li>Batismo;</li>
              <li>Igreja;</li>
              <li>Últimas coisas.</li>
            </ul>
