              <li>A salvação pela graça mediante a fé;</li>
              <li>A Igreja como Corpo de Cristo;</li>
              <li>A importância do ensino bíblico;</li>
              <li>O chamado e responsabilidade do ministério;</li>
              <li>A santidade cristã;</li>
              <li>A família segundo o propósito de Deus;</li>
              <li>A esperança da volta de Cristo;</li>
              <li>O juízo final e a eternidade.</li>
            </ul>
