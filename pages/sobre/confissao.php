            <h1 class="mb-4">Por que uma confissão de fé é importante?</h1>
            <h5 class="mb-3">Protege contra erros doutrinários</h5>
            <p>Uma confissão de fé ajuda a igreja a permanecer fiel à verdade bíblica. Ela serve como um guia para discernir entre o que é correto e o que é falso. A Bíblia ensina que devemos examinar aquilo que ouvimos.</p>

            <p><i>"Amados, não creiais a todo espírito, mas provai se os espíritos são de Deus..."1 João 4:1 </i></p>

            <p>Uma confissão ajuda a igreja a deixar claro:</p>
            <p>"Isso nós cremos porque encontramos fundamento nas Escrituras."</p>

            <h5 class="mb-3">Ensina novos cristãos</h5>
            <p>Uma pessoa que começa na fé possui muitas perguntas:</p>
            <ul>
              <li>Quem é Deus?</li>
              <li>Por que Jesus morreu?</li>
              <li>O que significa ser salvo?</li>
              <li>Qual o papel da Igreja?</li>
              <li>Qual a diferença entre Igreja e Cristo?</li>
            </ul>
            <p>Uma confissão de fé ajuda a responder essas perguntas de forma clara e fundamentada.</p>

            <h5 class="mb-3">Mantém uma identidade espiritual</h5>
            <p>Uma confissão de fé ajuda a igreja a manter uma identidade clara e coerente em relação aos seus valores e crenças.</p>
            <p>"Qual é a nossa base?"</p>
            <p>Paulo escreveu:</p>

            <p><i>"Porque ninguém pode pôr outro fundamento além do que já está posto, que é Jesus Cristo." (1 Coríntios 3:11)</i> </p>

            <h5 class="mb-3">Une pessoas em torno da verdade</h5>
            <p>Uma confissão de fé não existe para exaltar homens ou instituições, mas para declarar que une cistãos:</p>
            <ul>
              <li>Um Deus;</li>
              <li>Um Salvador;</li>
              <li>Um Espírito;</li>
              <li>Uma fé;</li>
              <li>Uma esperança</li>
            </ul>

            <p>Como Paulo escreveu:</p>

            <p><i>"Há um só corpo e um só Espírito, como também fostes chamados em uma só esperança da vossa vocação; um só Senhor, uma só fé, um só batismo." Efésios 4:4-5</i> </p>

            <h5 class="mb-3">Confissão de Fé do Bits de Fé</h5>

